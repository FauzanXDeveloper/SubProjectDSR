#!/usr/bin/env python3
"""Build data/geo/myPostcodes.js from the open postcode CSV.

Source (one of):
  - postcodes.csv            columns: state, city, postcode
  - heiswayi_postcodes.csv   columns: postcode, city, state, state_code

The output contains ONLY postcode / state / city reference data.
Never add customer data (addresses, names, IC numbers, income) to it.

Usage:
  python tools/build_geo.py --input "C:\\path\\to\\postcodes.csv" --out data/geo/myPostcodes.js
"""

import argparse
import csv
import json
import os
import re
import sys


def clean(value):
    text = str(value or "").strip()
    text = re.sub(r"\s+", " ", text)
    return text


def normalise_postcode(value):
    digits = re.sub(r"\D", "", str(value or ""))
    return digits[:5].zfill(5) if digits else ""


def read_rows(path):
    """Return [(postcode, state, city)] from either CSV layout."""
    with open(path, "r", encoding="utf-8-sig", newline="") as handle:
        sample = handle.read(2048)
        handle.seek(0)
        dialect = csv.Sniffer().sniff(sample, delimiters=",;\t") if sample else csv.excel
        reader = csv.DictReader(handle, dialect=dialect)
        fields = [str(name or "").strip().lower() for name in (reader.fieldnames or [])]

        rows = []
        for record in reader:
            lowered = {str(k or "").strip().lower(): v for k, v in record.items()}
            postcode = normalise_postcode(lowered.get("postcode"))
            state = clean(lowered.get("state"))
            city = clean(lowered.get("city"))
            if postcode and state and city:
                rows.append((postcode, state, city))
        return rows, fields


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", required=True, help="postcodes CSV file")
    parser.add_argument("--out", required=True, help="output JS file")
    parser.add_argument("--version", default="2026-11-27")
    args = parser.parse_args()

    if not os.path.isfile(args.input):
        sys.exit("input not found: " + args.input)

    rows, fields = read_rows(args.input)
    if not rows:
        sys.exit("no usable rows in " + args.input)

    # One entry per postcode. First occurrence wins; conflicts are reported.
    chosen = {}
    conflicts = 0
    for postcode, state, city in rows:
        if postcode in chosen:
            if chosen[postcode][0] != state or chosen[postcode][1] != city:
                conflicts += 1
            continue
        chosen[postcode] = (state, city)

    ordered = sorted(chosen.items(), key=lambda item: item[0])
    payload = "\n".join(
        "%s|%s|%s" % (postcode, state, city) for postcode, (state, city) in ordered
    )

    header = (
        "/* ---------------- Malaysia postcode reference ---------------- */\n"
        "/* Generated by tools/build_geo.py - do not edit by hand.\n"
        "   Source: %s (%s)\n"
        "   Contains postcode / state / city only - no customer data. */\n\n"
        % (os.path.basename(args.input), ", ".join(fields))
    )

    body = (
        "window.DSR_GEO = {\n"
        "  version: %s,\n"
        "  cols: 'postcode|state|city',\n"
        "  rows: %s\n"
        "};\n" % (json.dumps(args.version), json.dumps(payload))
    )

    out_dir = os.path.dirname(os.path.abspath(args.out))
    if out_dir and not os.path.isdir(out_dir):
        os.makedirs(out_dir)
    with open(args.out, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(header + body)

    size = os.path.getsize(args.out)
    print("postcodes : %d" % len(ordered))
    print("conflicts : %d (kept first occurrence)" % conflicts)
    print("output    : %s (%.1f KB)" % (args.out, size / 1024.0))


if __name__ == "__main__":
    main()
